"""Generate LLM instruction files for the migration."""

from __future__ import annotations

from datetime import datetime
from quickhatch.config import UserProfile
from quickhatch.analysis.driver_check import check_drivers


def generate_instructions(profile: UserProfile) -> str:
    """Generate comprehensive LLM instructions for setting up the Linux system."""
    sections = [
        _header(profile),
        _system_overview(profile),
        _hardware_section(profile),
        _driver_instructions(profile),
        _desktop_setup(profile),
        _apps_to_install(profile),
        _app_alternatives(profile),
        _files_to_transfer(profile),
        _settings_migration(profile),
        _ssh_section(profile),
        _additional_notes(profile),
        _checklist(profile),
    ]

    return "\n\n".join(sections)


def _header(profile: UserProfile) -> str:
    distro = profile.recommended_distro or "Linux"
    de = profile.recommended_de or "default"
    return f"""# QuickHatch Migration Instructions
## Setting up {distro} with {de}

**Generated:** {datetime.now().strftime('%Y-%m-%d %H:%M')}
**Migration type:** {profile.preferences.migration_type.replace('_', ' ').title()}
**Target distro:** {distro}
**Desktop environment:** {de}

---

> **For the AI Agent:** These instructions were generated by QuickHatch to help
> you set up the user's new Linux system. Follow each section in order. Ask the
> user for confirmation before making major changes. The profile.json file
> contains the complete machine-readable data.

---"""


def _system_overview(profile: UserProfile) -> str:
    hw = profile.hardware
    return f"""## System Overview

| Component | Details |
|-----------|---------|
| CPU | {hw.cpu} ({hw.cpu_cores} cores) |
| RAM | {hw.ram_gb:.1f} GB |
| GPUs | {', '.join(g.name for g in hw.gpus) or 'Unknown'} |
| WiFi | {', '.join(hw.wifi_adapters) or 'Unknown'} |
| Bluetooth | {'Yes' if hw.bluetooth else 'No'} |
| Boot Mode | {'UEFI' if hw.efi else 'Legacy BIOS'} |
| Disks | {', '.join(f'{d.device} ({d.total_gb:.0f} GB)' for d in hw.disks) or 'Unknown'} |"""


def _hardware_section(profile: UserProfile) -> str:
    hw = profile.hardware
    lines = ["## Hardware Configuration\n"]

    if hw.gpus:
        lines.append("### GPUs")
        for gpu in hw.gpus:
            lines.append(f"- **{gpu.name}** (Vendor: {gpu.vendor})")
            if gpu.vram_mb:
                lines.append(f"  - VRAM: {gpu.vram_mb} MB")
            if gpu.driver_version:
                lines.append(f"  - Windows driver: {gpu.driver_version}")

    if hw.wifi_adapters:
        lines.append("\n### WiFi Adapters")
        for adapter in hw.wifi_adapters:
            lines.append(f"- {adapter}")

    if hw.disks:
        lines.append("\n### Storage")
        for disk in hw.disks:
            lines.append(f"- **{disk.device}** ({disk.mountpoint})")
            lines.append(f"  - Size: {disk.total_gb:.0f} GB total, {disk.free_gb:.0f} GB free")
            lines.append(f"  - Filesystem: {disk.filesystem}")

    return "\n".join(lines)


def _driver_instructions(profile: UserProfile) -> str:
    drivers = check_drivers(profile.hardware)
    if not drivers:
        return "## Driver Setup\n\nNo special driver instructions needed."

    lines = ["## Driver Setup\n"]
    lines.append("Install these drivers after the base system is set up:\n")

    for d in drivers:
        status_icon = {"excellent": "OK", "supported": "~", "needs_driver": "!", "unknown": "?"}.get(d["status"], "?")
        lines.append(f"### [{status_icon}] {d['component']}")
        lines.append(f"**Action:** {d['action']}")
        if d["notes"]:
            lines.append(f"\n{d['notes']}")
        lines.append("")

    return "\n".join(lines)


def _desktop_setup(profile: UserProfile) -> str:
    prefs = profile.preferences
    de = profile.recommended_de or "default"

    lines = ["## Desktop Setup\n"]
    lines.append(f"**Target look:** {prefs.desktop_look.replace('_', ' ').title()}")
    lines.append(f"**Desktop environment:** {de}")
    lines.append(f"**Icon style:** {prefs.icon_style}")
    lines.append(f"**Wallpaper style:** {prefs.wallpaper_style}")

    lines.append("\n### Configuration Steps\n")

    # Icon recommendations
    icon_map = {
        "modern_flat": "Install Papirus icons: `sudo apt install papirus-icon-theme` or Fluent icons from GitHub",
        "classic": "Use the default icon theme or install Numix: `sudo apt install numix-icon-theme`",
        "colorful": "Install Tela Circle icons or Candy icons from gnome-look.org",
        "monochrome": "Install Adwaita icons (default GNOME) or Suru++",
    }
    if prefs.icon_style in icon_map:
        lines.append(f"1. **Icons:** {icon_map[prefs.icon_style]}")

    # Wallpaper recommendations
    wallpaper_map = {
        "dark": "Set a dark wallpaper. Search 'dark wallpaper' on unsplash.com or use the distro's dark collection",
        "light": "Set a bright wallpaper. Check the distro's default light wallpapers",
        "nature": "Download nature wallpapers from unsplash.com (search 'landscape')",
        "abstract": "Search for abstract/geometric wallpapers on unsplash.com",
        "minimal": "Use a solid color or subtle gradient. Most DEs support solid color wallpapers",
    }
    if prefs.wallpaper_style in wallpaper_map:
        lines.append(f"2. **Wallpaper:** {wallpaper_map[prefs.wallpaper_style]}")

    # Desktop environment specific
    if "KDE" in de:
        lines.append("3. **KDE tweaks:** Use System Settings to customize. KDE is highly configurable.")
        if prefs.desktop_look == "windows_like":
            lines.append("   - The default KDE layout is already Windows-like with taskbar at bottom")
    elif "GNOME" in de:
        lines.append("3. **GNOME tweaks:** Install `gnome-tweaks` for additional customization")
        if prefs.desktop_look == "macos_like":
            lines.append("   - Install Dash to Dock extension for a macOS-style dock")
            lines.append("   - `sudo apt install gnome-shell-extension-dash-to-dock`")
    elif "Cinnamon" in de:
        lines.append("3. **Cinnamon** is already Windows-like. Use System Settings > Themes to customize.")
    elif "Hyprland" in de or "i3" in de:
        lines.append("3. **Tiling WM:** Will need manual configuration.")
        lines.append("   - Copy example configs and customize keybindings")

    # Theme preference
    theme = profile.windows_settings.get("theme", "")
    if theme == "dark":
        lines.append(f"4. **Theme:** Set dark mode (user had dark mode on Windows)")
    elif theme == "light":
        lines.append(f"4. **Theme:** Set light mode (user had light mode on Windows)")

    return "\n".join(lines)


def _apps_to_install(profile: UserProfile) -> str:
    native = [a for a in profile.apps if a.compatibility == "native"]
    alternative = [a for a in profile.apps if a.compatibility == "alternative"]

    lines = ["## Applications to Install\n"]

    if native:
        lines.append("### Native Linux Apps (install directly)\n")
        lines.append("```bash")
        # Group common apps for batch install
        apt_names = []
        flatpak_names = []
        for app in native:
            name_lower = app.name.lower()
            if any(x in name_lower for x in ["firefox", "vlc", "git", "python", "blender"]):
                apt_names.append(app.name.lower().split()[0])
            else:
                flatpak_names.append(app.name)

        if apt_names:
            lines.append(f"# Via package manager")
            lines.append(f"sudo apt install {' '.join(apt_names[:10])}")
        if flatpak_names:
            lines.append(f"\n# Via Flatpak (install flatpak first if needed)")
            for name in flatpak_names[:10]:
                lines.append(f"# flatpak install flathub {name}")
        lines.append("```\n")

    if alternative:
        lines.append("### Linux Alternatives to Install\n")
        lines.append("| Windows App | Linux Alternative | Notes |")
        lines.append("|------------|-------------------|-------|")
        for app in alternative:
            lines.append(f"| {app.name} | {app.linux_alternative or '—'} | {app.compatibility_notes} |")

    # Wine apps
    wine_apps = [a for a in profile.apps if a.compatibility == "wine"]
    if wine_apps:
        lines.append("\n### Apps that Need Wine/Proton\n")
        lines.append("```bash")
        lines.append("# Install Wine")
        lines.append("sudo apt install wine64 winetricks")
        lines.append("```\n")
        for app in wine_apps:
            lines.append(f"- **{app.name}**: {app.compatibility_notes}")

    return "\n".join(lines)


def _app_alternatives(profile: UserProfile) -> str:
    no_support = [a for a in profile.apps if a.compatibility == "none"]
    if not no_support:
        return ""

    lines = ["## Apps Without Linux Support\n"]
    lines.append("These Windows apps don't have direct Linux equivalents:\n")
    for app in no_support:
        if app.compatibility_notes:
            lines.append(f"- **{app.name}**: {app.compatibility_notes}")
        else:
            lines.append(f"- **{app.name}**: No known Linux alternative")

    return "\n".join(lines)


def _files_to_transfer(profile: UserProfile) -> str:
    fs = profile.files_summary
    if not fs:
        return "## Files to Transfer\n\nNo file scan data available."

    lines = ["## Files to Transfer\n"]
    lines.append(f"**Total:** {fs.get('total_files', 0)} files, {fs.get('total_size_gb', 0):.1f} GB\n")

    dirs = fs.get("important_dirs", {})
    if dirs:
        lines.append("### Directories")
        for path, info in dirs.items():
            lines.append(f"- `{path}`: {info['files']} files, {info['size_gb']:.1f} GB")

    browsers = fs.get("browser_profiles", [])
    if browsers:
        lines.append("\n### Browser Data to Migrate")
        for browser in browsers:
            lines.append(f"- {browser}: Export bookmarks and sign in to sync")

    configs = fs.get("config_files", [])
    if configs:
        lines.append("\n### Config Files to Migrate")
        for config in configs:
            lines.append(f"- {config}")

    return "\n".join(lines)


def _settings_migration(profile: UserProfile) -> str:
    ws = profile.windows_settings
    if not ws:
        return ""

    lines = ["## Settings to Migrate\n"]
    if ws.get("theme"):
        lines.append(f"- **Theme:** {ws['theme']} mode")
    if ws.get("default_browser"):
        lines.append(f"- **Default browser:** {ws['default_browser']}")
    if ws.get("locale"):
        lines.append(f"- **Locale:** {ws['locale']}")
    if ws.get("timezone"):
        lines.append(f"- **Timezone:** {ws['timezone']}")
    if ws.get("keyboard_layout"):
        lines.append(f"- **Keyboard layout:** {ws['keyboard_layout']}")

    return "\n".join(lines)


def _ssh_section(profile: UserProfile) -> str:
    if not profile.ssh_public_key_path:
        return """## SSH Access

No SSH key was generated. To enable remote AI agent access:
```bash
ssh-keygen -t ed25519 -C "quickhatch"
sudo systemctl enable --now sshd
```"""

    return f"""## SSH Access

An SSH key was generated for this migration.
Public key file: `{profile.ssh_public_key_path}`

To enable remote access:
```bash
sudo systemctl enable --now sshd
# The public key has been added to ~/.ssh/authorized_keys by quickstart.sh
```"""


def _additional_notes(profile: UserProfile) -> str:
    notes = profile.preferences.additional_notes.strip()
    if not notes:
        return ""

    return f"""## Additional User Notes

{notes}"""


def _checklist(profile: UserProfile) -> str:
    use_cases = profile.preferences.use_cases

    lines = ["## Setup Checklist\n"]
    lines.append("- [ ] Install base system")
    lines.append("- [ ] Update system packages")
    lines.append("- [ ] Install GPU drivers")
    lines.append("- [ ] Configure WiFi/Bluetooth")
    lines.append("- [ ] Set up desktop environment and theme")
    lines.append("- [ ] Install essential applications")
    lines.append("- [ ] Install application alternatives")
    lines.append("- [ ] Transfer user files")
    lines.append("- [ ] Migrate browser bookmarks/data")
    lines.append("- [ ] Set up SSH for remote access")

    if "development" in use_cases:
        lines.append("- [ ] Install development tools (git, compilers, IDEs)")
        lines.append("- [ ] Set up development environment")
    if "gaming" in use_cases:
        lines.append("- [ ] Install Steam with Proton")
        lines.append("- [ ] Configure gamepad/controller support")
        lines.append("- [ ] Install MangoHud for performance monitoring")
    if "creative" in use_cases:
        lines.append("- [ ] Install creative applications (GIMP, Krita, etc.)")
    if "music_production" in use_cases:
        lines.append("- [ ] Set up JACK or PipeWire for low-latency audio")
        lines.append("- [ ] Install DAW and audio plugins")
    if "data_science" in use_cases:
        lines.append("- [ ] Install Python, Jupyter, and ML frameworks")
    if "sysadmin" in use_cases:
        lines.append("- [ ] Install Docker and containerization tools")
        lines.append("- [ ] Set up SSH keys and configs")

    lines.append("- [ ] Verify all hardware works correctly")
    lines.append("- [ ] Create backups/snapshots")

    return "\n".join(lines)
